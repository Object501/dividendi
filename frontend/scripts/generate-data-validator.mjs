import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const frontendDirectory = fileURLToPath(new URL("..", import.meta.url));
const repositoryDirectory = resolve(frontendDirectory, "..");
const schemaPath = resolve(
	repositoryDirectory,
	"schema/public-data-v1.schema.json",
);
const outputPath = resolve(
	frontendDirectory,
	"src/generated/publicDataValidators.js",
);
const declarationPath = resolve(
	frontendDirectory,
	"src/generated/publicDataValidators.d.ts",
);

const publicSchema = JSON.parse(await readFile(schemaPath, "utf-8"));
const snapshotSchemaId = `${publicSchema.$id}#/$defs/marketSnapshot`;
const historySchemaId = `${publicSchema.$id}#/$defs/historyDocument`;

const ajv = new Ajv2020({
	allErrors: true,
	code: { esm: true, lines: true, source: true },
	strict: true,
});
addFormats(ajv, ["date", "date-time"]);
ajv.addSchema(publicSchema);

const standaloneModule = standaloneCode(ajv, {
	validateHistoryDocument: historySchemaId,
	validateMarketSnapshot: snapshotSchemaId,
});
const generatedRuntimeImports = `import * as formatDefinitionsModule from "ajv-formats/dist/formats.js";\n\nconst formatDefinitions = "fullFormats" in formatDefinitionsModule\n\t? formatDefinitionsModule\n\t: formatDefinitionsModule.default;\nconst ucs2Length = (value) => [...value].length;\n\n`;
const generatedModule = `${generatedRuntimeImports}${standaloneModule
	.replaceAll('require("ajv-formats/dist/formats")', "formatDefinitions")
	.replaceAll(
		'require("ajv/dist/runtime/ucs2length").default',
		"ucs2Length",
	)}\n`;
if (generatedModule.includes("require(")) {
	throw new Error("Ajv standalone 生成了未处理的 CommonJS 运行时引用");
}
const generatedDeclaration = `// Generated by frontend/scripts/generate-data-validator.mjs. Do not edit.\n\nexport interface PublicDataValidationError {\n\treadonly instancePath: string;\n\treadonly keyword: string;\n\treadonly message?: string;\n\treadonly params: Readonly<Record<string, unknown>>;\n\treadonly schemaPath: string;\n}\n\nexport interface PublicDataValidator {\n\t(value: unknown): boolean;\n\treadonly errors: readonly PublicDataValidationError[] | null;\n}\n\nexport const validateHistoryDocument: PublicDataValidator;\nexport const validateMarketSnapshot: PublicDataValidator;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await Promise.all([
	writeFile(outputPath, generatedModule),
	writeFile(declarationPath, generatedDeclaration),
]);
